"""Generate the two CloudFront Functions (router and CSP header) from the validated declarations."""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Dict, List, Optional

from .buildinfo import EXTERNAL_HOST_KEYS, Agent, Shell
from .jsnode import run_function

FUNCTIONS_DIR = Path(__file__).resolve().parent.parent / "functions"
CONFIG_TOKEN = "__CONFIG__"
# CloudFront rejects a function larger than 10 KB; stay clear of the edge.
MAX_FUNCTION_BYTES = 10_000
WARN_FUNCTION_BYTES = 8_000
COGNITO_CONNECT = "https://cognito-idp.us-east-1.amazonaws.com"
COMMENT_LINE = re.compile(r"^[ \t]*//.*\n", re.M)


def _join(*groups: List[str]) -> str:
    seen: List[str] = []
    for group in groups:
        for item in group:
            if item not in seen:
                seen.append(item)
    return " ".join(seen)


def union_external_hosts(shell: Shell, agents: List[Agent]) -> Dict[str, List[str]]:
    """Every host any agent (or the shell) declared, per directive, each once and sorted. Every agent's screens now run on the
    same pages, so a host one agent needs is allowed for the whole site."""
    owners = [shell.external_hosts] + [agent.external_hosts for agent in agents]
    return {key: sorted({item for hosts in owners for item in hosts[key]}) for key in EXTERNAL_HOST_KEYS}


def content_security_policy(shell: Shell, agents: List[Agent]) -> str:
    """The one policy of the whole site: the dashboard's inline-script hashes and the union of the agents' external hosts."""
    hosts = union_external_hosts(shell, agents)
    return "; ".join(
        [
            "default-src 'self'",
            "script-src " + _join(["'self'"], shell.script_hashes),
            "style-src " + _join(["'self'", "'unsafe-inline'"], hosts["style-src"]),
            "img-src " + _join(["'self'", "data:"], hosts["img-src"]),
            "font-src " + _join(["'self'", "data:"], hosts["font-src"]),
            "connect-src " + _join(["'self'", COGNITO_CONNECT], hosts["connect-src"]),
            "frame-src 'none'",
            "frame-ancestors 'none'",
            "base-uri 'self'",
            "form-action 'self'",
        ]
    )


def _fill(template_name: str, config: object) -> str:
    template = (FUNCTIONS_DIR / template_name).read_text(encoding="utf-8")
    if template.count(CONFIG_TOKEN) != 1:
        raise ValueError(f"{template_name} must contain {CONFIG_TOKEN} exactly once")
    # The deployed code keeps one header line and no comment lines: every byte counts against the 10 KB limit.
    code = COMMENT_LINE.sub("", template)
    header = f"// Generated by infra/render.py from infra/functions/{template_name}; do not edit.\n"
    # ensure_ascii keeps the code ASCII, so no U+2028/U+2029 can end a JS string early.
    return header + code.replace(CONFIG_TOKEN, json.dumps(config, separators=(",", ":"), ensure_ascii=True))


def router_config(agents: List[Agent]) -> Dict[str, object]:
    api = [{"prefix": proxy.prefix, "origin": proxy.origin_path} for agent in agents for proxy in agent.api_proxy]
    api.sort(key=lambda rule: (-len(str(rule["prefix"])), str(rule["prefix"])))
    return {"api": api}


def render_router(agents: List[Agent]) -> str:
    return _fill("router.template.js", router_config(agents))


def render_headers(shell: Shell, agents: List[Agent]) -> str:
    return _fill("headers.template.js", content_security_policy(shell, agents))


def check_size(name: str, code: str, warnings: Optional[List[str]] = None) -> None:
    size = len(code.encode("utf-8"))
    if size >= MAX_FUNCTION_BYTES:
        raise ValueError(
            f"{name} is {size} bytes; CloudFront Functions may be at most 10 KB (we stop at {MAX_FUNCTION_BYTES}). "
            "The policy grows with the dashboard build's inline scripts and the agents' external hosts (infra/README.md, 'If the headers function outgrows 10 KB')"
        )
    if warnings is not None and size >= WARN_FUNCTION_BYTES:
        warnings.append(f"{name} is {size} of {MAX_FUNCTION_BYTES} bytes: not much room left (infra/README.md, 'If the headers function outgrows 10 KB')")


def self_check(router: str, headers: str, agents: List[Agent]) -> None:
    """Load both functions in Node and call them, so a syntax error or a bad regex stops the render."""
    probes = [("/", "/index.html")]
    for agent in agents:
        for proxy in agent.api_proxy:
            probes.append((proxy.prefix + "ping", proxy.origin_path + "ping"))
    events = [{"request": {"uri": uri, "method": "GET", "headers": {}}} for uri, _ in probes]
    for (uri, wanted), routed in zip(probes, run_function(router, events)):
        if routed.get("uri") != wanted:
            raise ValueError(f"router self-check: {uri!r} became {routed.get('uri')!r}, expected {wanted!r}")
    event = {
        "request": {"uri": "/", "method": "GET", "headers": {}},
        "response": {"statusCode": 200, "headers": {"content-type": {"value": "text/html"}}},
    }
    answered = run_function(headers, [event])[0]
    if "content-security-policy" not in answered.get("headers", {}):
        raise ValueError("headers self-check: an HTML response got no content-security-policy")
